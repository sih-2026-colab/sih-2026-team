clear;
clc;
close all;


%% =========================================================
% AUTONEX 2-D TRAJECTORY GENERATION TEST
%% =========================================================

actors = ...
    create_highway_scenario();


ego = ...
    actors(1);


%% Dense horizon only for visualizing the curves

horizons = ...
    0:0.10:3.0;


candidates = ...
    generate_2d_candidate_set( ...
        ego, ...
        horizons);


fprintf('\n');
fprintf('============================================================\n');
fprintf(' AutoNex 2-D Candidate Trajectory Generator\n');
fprintf('============================================================\n\n');


fprintf( ...
    'Generated %d candidate trajectories.\n\n', ...
    length(candidates));


%% =========================================================
% PRINT CANDIDATES
%% =========================================================

for i = 1:length(candidates)

    fprintf( ...
        ['Candidate %2d | ' ...
         '%-18s | ' ...
         'Speed=%5.1f km/h | ' ...
         'TargetY=%4.2f m\n'], ...
        candidates(i).id, ...
        candidates(i).name, ...
        candidates(i).targetSpeedKmh, ...
        candidates(i).targetY);

end


%% =========================================================
% VISUALIZE
%% =========================================================

figure( ...
    'Name', ...
    'AutoNex 2-D Candidate Trajectories');


hold on;
grid on;


%% Road edges

plot( ...
    [ego.x ego.x+70], ...
    [-1.75 -1.75], ...
    'k', ...
    'LineWidth',2);


plot( ...
    [ego.x ego.x+70], ...
    [8.75 8.75], ...
    'k', ...
    'LineWidth',2);


%% Lane separators

plot( ...
    [ego.x ego.x+70], ...
    [1.75 1.75], ...
    'k--');


plot( ...
    [ego.x ego.x+70], ...
    [5.25 5.25], ...
    'k--');


%% Lane centers

plot( ...
    [ego.x ego.x+70], ...
    [0 0], ...
    ':');


plot( ...
    [ego.x ego.x+70], ...
    [3.5 3.5], ...
    ':');


plot( ...
    [ego.x ego.x+70], ...
    [7 7], ...
    ':');


%% =========================================================
% DRAW ALL TRAJECTORIES
%% =========================================================

for i = 1:length(candidates)

    plot( ...
        candidates(i).trajectory.x, ...
        candidates(i).trajectory.y, ...
        'LineWidth',1.2);

end


%% Ego start

plot( ...
    ego.x, ...
    ego.y, ...
    's', ...
    'MarkerSize',12, ...
    'LineWidth',3);


